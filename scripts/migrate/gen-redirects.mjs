#!/usr/bin/env node
// gen-redirects.mjs — WU0.2: single source of the cutover redirect map (design D5).
//
// Convention (D1): every source (VuePress 2) URL is its path plus a trailing
// slash; the docmd URL is the same path without the slash. Directory-index
// forms (pages imported from README.md) follow the same rule at their dir.
// One entry per md file in the imported docs/ tree.
//
// Output:
//   <root>/redirects.json — canonical {"redirects": [{from, to}, ...]} sorted by from.
//     NOTE (R10): the exact docmd config property is smoke-verified against the
//     installed 0.9.4 in WU0.8; this file is the reviewable canonical map and the
//     WU0.4 config assembly reads it.
//   <root>/redirects-manifest.md — totals, per-module counts, 10-entry sample.
//
// Usage: node gen-redirects.mjs <targetDocsDir> <rootOut> [expectedMdCount=1284]

import { writeFileSync, readdirSync, statSync, mkdirSync } from 'node:fs';
import { resolve, join, dirname } from 'node:path';

const [argDocs, argRoot, argExpected] = process.argv.slice(2);
if (!argDocs || !argRoot) {
  console.error('Usage: node gen-redirects.mjs <targetDocsDir> <rootOut> [expectedMdCount]');
  process.exit(2);
}
const docsDir = resolve(argDocs);
const root = resolve(argRoot);
const expected = Number(argExpected || 1284);

function walk(dir, out) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (name.endsWith('.md')) out.push(p);
  }
  return out;
}

const entries = [];
for (const file of walk(docsDir, [])) {
  const rel = file.slice(docsDir.length + 1).slice(0, -3); // strip ./ and .md
  let from;
  let to;
  if (rel.endsWith('/index') || rel === 'index') {
    const dirPath = rel === 'index' ? '' : rel.slice(0, -6); // strip '/index'
    from = dirPath === '' ? '/' : `/${dirPath}/`;
    to = dirPath === '' ? '/' : `/${dirPath}`;
  } else {
    from = `/${rel}/`;
    to = `/${rel}`;
  }
  entries.push({ from, to });
}

entries.sort((a, b) => (a.from < b.from ? -1 : a.from > b.from ? 1 : 0));
if (entries.length !== expected) {
  console.error(`COUNT MISMATCH: expected ${expected} entries, produced ${entries.length}`);
  process.exit(1);
}

mkdirSync(root, { recursive: true });
writeFileSync(join(root, 'redirects.json'), `${JSON.stringify({ redirects: entries }, null, 2)}\n`);

const perModule = {};
for (const e of entries) {
  const top = e.from.split('/')[1] || '(root)';
  perModule[top] = (perModule[top] || 0) + 1;
}
const sample = entries.slice(0, 10).map((e) => `| \`${e.from}\` | \`${e.to}\` |`).join('\n');
const manifest = [
  `# Redirects manifest`,
  ``,
  `Generated by \`scripts/migrate/gen-redirects.mjs\` from the imported docs/ tree.`,
  ``,
  `- Total entries: **${entries.length}** (expected ${expected})`,
  `- Convention: source URL = path + trailing slash (VuePress 2); target = path without slash (docmd).`,
  `- R10: exact docmd config property smoke-verified in WU0.8 against installed 0.9.4.`,
  ``,
  `## Per top module`,
  ``,
  ...Object.entries(perModule).sort().map(([k, n]) => `- ${k}: ${n}`),
  ``,
  `## Sample (first 10)`,
  ``,
  `| from | to |`,
  `|---|---|`,
  sample,
  ``,
].join('\n');
writeFileSync(join(root, 'redirects-manifest.md'), manifest);
console.log(`redirects.json: ${entries.length} entries -> ${join(root, 'redirects.json')}`);
console.log(`redirects-manifest.md -> ${join(root, 'redirects-manifest.md')}`);
for (const [k, n] of Object.entries(perModule).sort()) console.log(`  ${k}: ${n}`);
