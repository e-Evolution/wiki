#!/usr/bin/env node
// gen-redirects.mjs — WU0.2: single source of the cutover redirect map (design D5).
//
// Convention (D1): every source (VuePress 2) URL is its path plus a trailing
// slash; the docmd URL is the same path without the slash. Directory-index
// forms (pages imported from README.md) follow the same rule at their dir.
// One entry per md file in the imported docs/ tree.
//
// URL convention (verified WU0.3/WU0.4, 0.9.4): docmd canonical URLs KEEP the
// trailing slash (301 -> 200), exactly like the old VuePress 2 URLs. Therefore:
//   from (old URL)  = path + trailing slash
//   to   (new URL)  = SAME path + trailing slash (canonical identity)
//
// R10 (closed from 0.9.4 dist source): config `redirects` is a MAP
// {from: to} emitted as static meta-refresh pages, and an entry whose `from`
// equals a built page path OVERWRITES that page. So:
//   <root>/redirects-manifest.md — COVERAGE manifest: one row per source URL
//     (1,284) — the cutover checklist and spec artifact (D5).
//   <root>/redirects-map.json    — the config map: ONLY non-identity entries
//     (from !== to). Under D1 identity this is expected to be EMPTY; the
//     WU0.4 docmd.config.json `redirects` section is regenerated from it.
//
// Usage: node gen-redirects.mjs <targetDocsDir> <rootOut> [expectedMdCount=1284]

import { writeFileSync, readdirSync, statSync, mkdirSync } from 'node:fs';
import { resolve, join, dirname } from 'node:path';

const [argDocs, argRoot, argExpected] = process.argv.slice(2);
if (!argDocs || !argRoot) {
  console.error('Usage: node gen-redirects.mjs <targetDocsDir> <rootOut> [expectedMdCount]');
  process.exit(2);
}
const docsDir = resolve(argDocs);
const root = resolve(argRoot);
const expected = Number(argExpected || 1284);

function walk(dir, out) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (name.endsWith('.md')) out.push(p);
  }
  return out;
}

// docmd slugifies each route/output segment (dist engine/generator.js
// slugifyOutputPath + utils/auto-router.js slugifySegment): spaces -> '-',
// other unsafe URL chars -> '-', collapse '---', trim leading/trailing '-'.
// 'from' keeps the exact OLD source URL (legacy site served it verbatim);
// 'to' is the docmd BUILT URL, which may differ only where a filename needs
// slugification.
function slugifySegment(seg) {
  return (
    seg
      .replace(/\s+/g, '-')
      .replace(/[^a-zA-Z0-9\-_.~]/g, '-')
      .replace(/-{2,}/g, '-')
      .replace(/^-+|-+$/g, '') || seg
  );
}
function slugifyPath(p) {
  return p.split('/').map(slugifySegment).join('/');
}

const entries = [];
for (const file of walk(docsDir, [])) {
  const rel = file.slice(docsDir.length + 1).slice(0, -3); // strip ./ and .md
  let from;
  let to;
  if (rel.endsWith('/index') || rel === 'index') {
    const dirPath = rel === 'index' ? '' : rel.slice(0, -6); // strip '/index'
    const slugDir = slugifyPath(dirPath);
    from = dirPath === '' ? '/' : `/${dirPath}/`;
    to = slugDir === '' ? '/' : `/${slugDir}/`;
  } else {
    from = `/${rel}/`;
    to = `/${slugifyPath(rel)}/`;
  }
  entries.push({ from, to });
}

entries.sort((a, b) => (a.from < b.from ? -1 : a.from > b.from ? 1 : 0));
if (entries.length !== expected) {
  console.error(`COUNT MISMATCH: expected ${expected} entries, produced ${entries.length}`);
  process.exit(1);
}

// Coverage manifest (all entries, sorted) + config map (non-identity only).
const identity = entries.filter((e) => e.from === e.to);
const configMap = {};
for (const e of entries) {
  if (e.from !== e.to) configMap[e.from] = e.to;
}
mkdirSync(root, { recursive: true });
writeFileSync(join(root, 'redirects-map.json'), `${JSON.stringify(configMap, null, 2)}\n`);

const perModule = {};
for (const e of entries) {
  const top = e.from.split('/')[1] || '(root)';
  perModule[top] = (perModule[top] || 0) + 1;
}
const sample = entries.slice(0, 10).map((e) => `| \`${e.from}\` | \`${e.to}\` |`).join('\n');
const manifest = [
  `# Redirects coverage manifest`,
  ``,
  `Generated by \`scripts/migrate/gen-redirects.mjs\` from the imported docs/ tree.`,
  ``,
  `- Source URLs covered: **${entries.length}** (expected ${expected})`,
  `- Identity (old URL already served at the new URL): **${identity.length}**`,
  `- Config-map entries (non-identity, written to docmd.config.json \`redirects\`): **${Object.keys(configMap).length}**`,
  `- Convention: docmd canonical URLs keep the trailing slash (verified 0.9.4: 301 -> 200), identical to the old VuePress 2 URLs.`,
  `- R10 (closed): config \`redirects\` is a {from: to} map of static meta-refresh pages; identity entries would overwrite real pages, so only non-identity entries are ever emitted.`,
  ``,
  `This manifest is the cutover checklist (D5): every old URL is accounted for;`,
  `a zero config-map means the cutover needs no redirects.`,
  ``,
  `## Per top module`,
  ``,
  ...Object.entries(perModule).sort().map(([k, n]) => `- ${k}: ${n}`),
  ``,
  `## Sample (first 10)`,
  ``,
  `| from (old URL) | to (new URL) |`,
  `|---|---|`,
  sample,
  ``,
].join('\n');
writeFileSync(join(root, 'redirects-manifest.md'), manifest);
console.log(`coverage manifest: ${entries.length} URLs (${identity.length} identity) -> ${join(root, 'redirects-manifest.md')}`);
console.log(`config map: ${Object.keys(configMap).length} non-identity entries -> ${join(root, 'redirects-map.json')}`);
console.log(`redirects-manifest.md -> ${join(root, 'redirects-manifest.md')}`);
for (const [k, n] of Object.entries(perModule).sort()) console.log(`  ${k}: ${n}`);
